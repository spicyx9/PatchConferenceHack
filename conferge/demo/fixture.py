"""Serialize / load ``fixtures/demo.json`` (owned by window 13).

Each domain list is a ``DataEnvelope`` with ``source_mode="fixture"`` and a
``RunReport`` whose termination is ``not_applicable`` (nothing was collected).
The file also embeds the expected replay so consumers can check determinism.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from conferge.core.schemas import (
    Company,
    Conference,
    DataEnvelope,
    Event,
    FlightOffer,
    Goal,
    Lodging,
    Person,
    RunReport,
)
from conferge.demo.engine import DEFAULT_CHANGE, replay
from conferge.demo.seed import FIXED_COLLECTED_AT, PROVIDER, SEED, DemoUser, DemoWorld, build_world

FIXTURE_PATH = Path(__file__).resolve().parents[2] / "fixtures" / "demo.json"
FIXTURE_VERSION = 1
DISCLAIMER = (
    "Synthetic offline demo data. All people, companies, side events, sessions, venues, "
    "prices and attendance are fictional or simulated (source_mode=fixture). Only the anchor "
    "conference name, dates and venue come from docs/knowledge/03-demo-scenario.md and are "
    "not live-verified. Never present this file as live data."
)


def _report(count: int) -> RunReport:
    return RunReport(
        provider=PROVIDER,
        started_at=FIXED_COLLECTED_AT,
        finished_at=FIXED_COLLECTED_AT,
        status="ok",
        termination="not_applicable",
        source_mode="fixture",
        fetched_count=count,
        unique_count=count,
        pages=0,
        warnings=["fixture: generated by scripts/gen_fixtures.py, no provider was called"],
    )


def _envelope(items: list[BaseModel]) -> dict[str, Any]:
    env = DataEnvelope[type(items[0])](
        items=items,
        source_mode="fixture",
        status="ok",
        collected_at=FIXED_COLLECTED_AT,
        reports=[_report(len(items))],
    )
    return env.model_dump(mode="json")


def _user(user: DemoUser) -> dict[str, Any]:
    return {
        "id": user.id,
        "label": user.label,
        "home_city": user.home_city,
        "origin_airports": list(user.origin_airports),
        "destination_airports": list(user.destination_airports),
        "depart_on": user.depart_on.isoformat(),
        "return_on": user.return_on.isoformat(),
        "adults": user.adults,
        "cabin": user.cabin,
        "budget_usd": str(user.budget_usd),
        "goal_text": user.goal_text,
        "source_mode": "fixture",
    }


def build_fixture(world: DemoWorld | None = None) -> dict[str, Any]:
    w = world or build_world()
    return {
        "fixture_version": FIXTURE_VERSION,
        "source_mode": "fixture",
        "seed": SEED,
        "generated_by": "scripts/gen_fixtures.py",
        "collected_at": FIXED_COLLECTED_AT.isoformat(),
        "disclaimer": DISCLAIMER,
        "user": _user(w.user),
        "conference": w.conference.model_dump(mode="json"),
        "goals": [g.model_dump(mode="json") for g in w.goals],
        "companies": _envelope(w.companies),
        "people": _envelope(w.people),
        "events": _envelope(w.events),
        "lodging": _envelope(w.lodging),
        "flights": _envelope(w.flights),
        "scenarios": [DEFAULT_CHANGE],
        "expected_replay": json.loads(json.dumps(replay(w))),
    }


def dumps(data: dict[str, Any]) -> str:
    return json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def load_fixture(path: Path = FIXTURE_PATH) -> dict[str, Any]:
    """Load and validate every record of ``fixtures/demo.json`` against core schemas."""
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("source_mode") != "fixture":
        raise ValueError("demo fixture must declare source_mode=fixture")
    parsed: dict[str, Any] = dict(data)
    parsed["conference"] = Conference.model_validate(data["conference"])
    parsed["goals"] = [Goal.model_validate(g) for g in data["goals"]]
    for key, model in (("companies", Company), ("people", Person), ("events", Event),
                       ("lodging", Lodging), ("flights", FlightOffer)):
        parsed[key] = DataEnvelope[model].model_validate(data[key])
    return parsed


def world_from_fixture(path: Path = FIXTURE_PATH) -> DemoWorld:
    parsed = load_fixture(path)
    return DemoWorld(
        user=DemoUser(),
        conference=parsed["conference"],
        goals=parsed["goals"],
        companies=parsed["companies"].items,
        people=parsed["people"].items,
        events=parsed["events"].items,
        lodging=parsed["lodging"].items,
        flights=parsed["flights"].items,
    )
