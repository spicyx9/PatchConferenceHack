"""Probe for window 13: verify the offline demo replays and write ``probes/demo.md``.

No network, no secrets. Everything reported here is fixture data.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from conferge.demo.engine import replay
from conferge.demo.fixture import FIXTURE_PATH, build_fixture, dumps, load_fixture, world_from_fixture

OUT = Path(__file__).resolve().parents[2] / "probes" / "demo.md"


def main() -> int:
    errors: list[str] = []
    run_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
    fresh = FIXTURE_PATH.exists() and FIXTURE_PATH.read_text(encoding="utf-8") == dumps(
        build_fixture()
    )
    if not fresh:
        errors.append("fixtures/demo.json missing or stale (run scripts/gen_fixtures.py)")
    counts: dict[str, int] = {}
    replay_ok = False
    if FIXTURE_PATH.exists():
        try:
            parsed = load_fixture()
            counts = {k: len(parsed[k].items) for k in
                      ("events", "people", "companies", "lodging", "flights")}
            from_file = json.loads(json.dumps(replay(world_from_fixture())))
            replay_ok = from_file == parsed["expected_replay"]
            if not replay_ok:
                errors.append("replay from fixtures/demo.json differs from expected_replay")
        except Exception as exc:  # report, never hide
            errors.append(f"fixture load failed: {type(exc).__name__}: {exc}")
    result = replay()
    status = "ok" if not errors else "failed"
    lines = [
        "# Probe: demo (window 13)",
        "",
        f"- run_at: {run_at}",
        "- source: `fixtures/demo.json` generated by `scripts/gen_fixtures.py`",
        "- source_mode: **fixture** (no live or cached record; no provider called)",
        "- network: none; secrets: none",
        f"- status: **{status}**, termination: not_applicable",
        f"- fixture up to date: {fresh}",
        f"- deterministic replay from file matches expected: {replay_ok}",
        "- counts (raw = unique, synthetic): "
        + ", ".join(f"{k}={v}" for k, v in counts.items()),
        "",
        "## Scripted outcome",
        "",
        f"- plan: {', '.join(e['id'] for e in result['plan']['events'])}",
        f"- clash: {result['plan']['clashes'][0]['explanation'] if result['plan']['clashes'] else 'none'}",
        f"- change: {result['change']['event_id']} -> {result['change']['type']}",
        f"- diff: removed {result['diff']['removed']}, added {result['diff']['added']}",
        f"- travel: {result['travel']['flight_id']} + {result['travel']['lodging_id']}, "
        f"simulated total {result['travel']['simulated_total_usd']} USD ({result['travel']['label']})",
        "",
        "## Errors",
        "",
        *([f"- {e}" for e in errors] or ["- none"]),
        "",
        "Live behaviour: not applicable. This window ships no connector; live data comes from",
        "source windows and must never be replaced silently by this fixture.",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} status={status}")
    return 0 if status == "ok" else 1


if __name__ == "__main__":
    raise SystemExit(main())
